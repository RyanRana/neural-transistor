"""Emit a connectome circuit as plain C for a microcontroller.

The generated code is freestanding: no malloc, no libc at all, no floats in the hot
loop, and every array is ``const`` so it links into flash instead of RAM. It builds with
any C99 compiler and needs no runtime.

"No libc" is meant literally, including headers. The runtime used to ``#include
<string.h>`` for three ``memset`` calls, which costs nothing on a hosted build and then
fails to compile against a bare-metal toolchain that ships without newlib -- the exact
configuration this code exists for. The fills are open-coded instead.

Two properties of the biology make the kernel unusually cheap, and the emitter is built
around both.

**Dale's law hoists the sign out of the inner loop.** A neuron is excitatory or
inhibitory, not both, so sign is a property of the presynaptic cell -- constant across
an entire CSR row. The multiply by +-1 leaves the per-edge path and becomes one branch
per firing neuron. A general sparse matmul cannot do this; a connectome always can.

**Firing is sparse, so propagation is event-driven.** Only neurons that fired this tick
walk their row. Measured sparsity on fly circuits sits near 10% active, so the inner
loop runs on roughly a tenth of the edges per tick. This is the same reason the biology
is cheap, and it survives compilation.

Weights are stored as codes into a small int16 codebook rather than as quantized
values. Synapse counts are log-distributed over four orders of magnitude, so a codebook
holds the tail exactly while the code stays at 4 or 8 bits, and the lookup costs one
load from flash.
"""

from __future__ import annotations

import textwrap
from dataclasses import dataclass
from pathlib import Path

import numpy as np

from neuraltransistor.ir.graph import CircuitIR
from neuraltransistor.quant.quantize import quantize_weights


@dataclass
class EmitReport:
    flash_B: int
    ram_B: int
    edges: int
    neurons: int
    weight_bits: int
    index_bits: int
    macs_per_tick_dense: int
    files: list

    def __str__(self):
        return (f"C emit: {self.neurons:,} neurons / {self.edges:,} edges | "
                f"flash {self.flash_B/1024:.1f} KB, ram {self.ram_B/1024:.1f} KB | "
                f"w{self.weight_bits} i{self.index_bits}")


def _c_array(name: str, arr: np.ndarray, ctype: str, per_line: int = 16,
             qualifier: str = "const") -> str:
    """Emit a file-scope array.

    ``const`` at file scope in C has EXTERNAL linkage, so the runtime translation unit
    can see it. Writing ``static const`` here compiles fine and then fails at link with
    ten undefined symbols, which is a confusing way to learn this.
    """
    vals = arr.tolist()
    body = []
    for i in range(0, len(vals), per_line):
        body.append("  " + ", ".join(str(int(v)) for v in vals[i:i + per_line]) + ",")
    return (f"{qualifier} {ctype} {name}[{len(vals)}] = {{\n"
            + "\n".join(body) + "\n};\n")


def _pick_ctype(bits: int, signed: bool = False) -> str:
    if bits <= 8:
        return "int8_t" if signed else "uint8_t"
    if bits <= 16:
        return "int16_t" if signed else "uint16_t"
    return "int32_t" if signed else "uint32_t"


def emit_c(ir: CircuitIR, outdir: str | Path, weight_bits: int = 8,
           scheme: str = "log", prefix: str = None) -> EmitReport:
    """Write ``<prefix>.h`` / ``<prefix>.c`` / ``<prefix>_runtime.c`` into ``outdir``."""
    outdir = Path(outdir)
    outdir.mkdir(parents=True, exist_ok=True)
    prefix = prefix or ir.name.replace("-", "_")
    N, E = ir.n_neurons, ir.n_edges

    codes, book = quantize_weights(ir.weight, weight_bits, scheme)
    book_i = np.round(book).astype(np.int16)

    idx_bits = 8 if N <= 256 else (16 if N <= 65536 else 32)
    idx_t = _pick_ctype(idx_bits)
    code_t = _pick_ctype(max(weight_bits, 8))
    ptr_t = "uint32_t" if E > 65535 else "uint16_t"

    # --- data file -----------------------------------------------------------
    data = [f'/* generated by neuraltransistor -- circuit "{ir.name}"',
            f' * {N:,} neurons, {E:,} edges, {ir.n_synapses:,} synapses',
            f' * fingerprint {ir.fingerprint()}',
            f' * provenance: {ir.provenance.get("dataset","?")} '
            f'selector={ir.provenance.get("selector","?")}',
            " * DO NOT EDIT -- regenerate with `neuraltransistor emit`",
            " */",
            f'#include "{prefix}.h"', ""]
    data.append(_c_array(f"{prefix}_indptr", ir.indptr, ptr_t, 12))
    data.append(_c_array(f"{prefix}_index", ir.indices, idx_t, 16))
    data.append(_c_array(f"{prefix}_code", codes, code_t, 24))
    data.append(_c_array(f"{prefix}_book", book_i, "int16_t", 12))
    data.append(_c_array(f"{prefix}_sign", ir.sign, "int8_t", 24))

    dyn = ir.dynamics
    # Fixed-point dynamics: Q8.8. decay = exp(-dt/tau) scaled by 256.
    decay = np.exp(-dyn.dt / np.maximum(dyn.tau_m, 1e-6))
    data.append(_c_array(f"{prefix}_decay_q8", np.round(decay * 256).astype(np.uint16),
                         "uint16_t", 16))
    data.append(_c_array(f"{prefix}_thresh", np.round(dyn.threshold * 256).astype(np.int16),
                         "int16_t", 16))

    has_mod = ir.n_mod_edges > 0
    if has_mod:
        data.append(_c_array(f"{prefix}_mod_pre", ir.mod_pre, idx_t, 16))
        data.append(_c_array(f"{prefix}_mod_post", ir.mod_post, idx_t, 16))
        data.append(_c_array(f"{prefix}_mod_w", np.clip(ir.mod_weight, 0, 255).astype(np.uint8),
                             "uint8_t", 24))

    # --- header --------------------------------------------------------------
    ports_h = []
    for p in ir.in_ports:
        ports_h.append(_c_array(f"{prefix}_in_{p.name}", p.neurons, idx_t, 16,
                                qualifier="extern const").replace(" = {", ";").split(";")[0] + ";")
    hdr = textwrap.dedent(f"""\
        /* generated by neuraltransistor -- circuit "{ir.name}" */
        #ifndef {prefix.upper()}_H
        #define {prefix.upper()}_H
        #include <stdint.h>

        #define {prefix.upper()}_N_NEURONS {N}
        #define {prefix.upper()}_N_EDGES   {E}
        #define {prefix.upper()}_N_MOD     {ir.n_mod_edges}
        #define {prefix.upper()}_DT_US     {int(dyn.dt * 1e6)}
        #define {prefix.upper()}_WEIGHT_BITS {weight_bits}

        /* Mutable state. This is the only RAM the circuit needs. */
        typedef struct {{
            int16_t v[{N}];        /* membrane potential, Q8.8 */
            uint8_t fired[{N}];    /* spike output of the last tick */
            uint8_t refrac[{N}];   /* ticks remaining in refractory */
            {"uint8_t gain[" + str(N) + "];  /* modulatory gain, Q0.8, 255 = unity */" if has_mod else ""}
        }} {prefix}_state_t;

        void {prefix}_reset({prefix}_state_t *s);
        /* Advance one tick. `input` is Q8.8 current injected per neuron, or NULL. */
        void {prefix}_tick({prefix}_state_t *s, const int16_t *input);

        #endif
        """)

    # --- runtime -------------------------------------------------------------
    mod_block = ""
    if has_mod:
        mod_block = textwrap.dedent(f"""
            /* Modulatory pass: dopaminergic/octopaminergic terminals SCALE their
             * target's gain rather than injecting current. Additive compilation of
             * these edges is the single most common way to lose gating behaviour. */
            for (uint32_t k = 0; k < {ir.n_mod_edges}u; ++k) {{
                if (!s->fired[{prefix}_mod_pre[k]]) continue;
                uint32_t t = {prefix}_mod_post[k];
                int32_t g = (int32_t)s->gain[t] + (int32_t){prefix}_mod_w[k];
                s->gain[t] = (uint8_t)(g > 255 ? 255 : g);
            }}
        """)

    gain_apply = (f"acc = (acc * (int32_t)s->gain[i]) >> 8;" if has_mod else "")
    mod_externs = ("" if not has_mod else
                   f"extern const {idx_t} {prefix}_mod_pre[];\n"
                   f"        extern const {idx_t} {prefix}_mod_post[];\n"
                   f"        extern const uint8_t {prefix}_mod_w[];")

    gain_decay = (f"""
            /* gain relaxes back toward unity so modulation is transient */
            for (uint32_t i = 0; i < N; ++i) {{
                int32_t g = (int32_t)s->gain[i];
                s->gain[i] = (uint8_t)(g + ((128 - g) >> 5));
            }}""" if has_mod else "")

    rt = textwrap.dedent(f"""\
        /* generated by neuraltransistor -- runtime for "{ir.name}" */
        #include "{prefix}.h"

        extern const {ptr_t} {prefix}_indptr[];
        extern const {idx_t} {prefix}_index[];
        extern const {code_t} {prefix}_code[];
        extern const int16_t {prefix}_book[];
        extern const int8_t  {prefix}_sign[];
        extern const uint16_t {prefix}_decay_q8[];
        extern const int16_t {prefix}_thresh[];
        {mod_externs}
        #define N {prefix.upper()}_N_NEURONS

        static int32_t acc_buf[N];

        /* open-coded byte fill: this runtime pulls in no libc, not even a header */
        static void {prefix}_fill8(uint8_t *d, uint8_t v, uint32_t n) {{
            while (n--) *d++ = v;
        }}

        void {prefix}_reset({prefix}_state_t *s) {{
            {prefix}_fill8((uint8_t *)s, 0, sizeof(*s));
            {f"{prefix}_fill8(s->gain, 128, sizeof(s->gain));" if has_mod else ""}
        }}

        void {prefix}_tick({prefix}_state_t *s, const int16_t *input) {{
            for (uint32_t i = 0; i < N; ++i) acc_buf[i] = 0;

            /* Event-driven propagation. Only neurons that fired last tick walk
             * their row, and Dale's law means the sign is constant across that row,
             * so the +-1 never enters the inner loop. */
            for (uint32_t i = 0; i < N; ++i) {{
                if (!s->fired[i]) continue;
                const int32_t sg = (int32_t){prefix}_sign[i];
                const uint32_t a = {prefix}_indptr[i], b = {prefix}_indptr[i + 1];
                for (uint32_t k = a; k < b; ++k) {{
                    acc_buf[{prefix}_index[k]] += sg * (int32_t){prefix}_book[{prefix}_code[k]];
                }}
            }}
        {mod_block}
            for (uint32_t i = 0; i < N; ++i) {{
                int32_t acc = acc_buf[i];
                if (input) acc += (int32_t)input[i];
                {gain_apply}
                if (s->refrac[i]) {{ s->refrac[i]--; s->v[i] = 0; s->fired[i] = 0; continue; }}
                int32_t v = ((int32_t)s->v[i] * (int32_t){prefix}_decay_q8[i]) >> 8;
                v += acc;
                if (v >  32767) v =  32767;
                if (v < -32768) v = -32768;
                if (v >= (int32_t){prefix}_thresh[i]) {{
                    s->fired[i] = 1; s->v[i] = 0; s->refrac[i] = 4;
                }} else {{
                    s->fired[i] = 0; s->v[i] = (int16_t)v;
                }}
            }}
        {gain_decay}
        }}
        """)

    def _tidy(src: str) -> str:
        lines = [ln[8:] if ln.startswith(" " * 8) else ln for ln in src.splitlines()]
        return "\n".join(lines) + "\n"

    (outdir / f"{prefix}.h").write_text(_tidy(hdr))
    (outdir / f"{prefix}.c").write_text("\n".join(data))
    (outdir / f"{prefix}_runtime.c").write_text(_tidy(rt))

    flash = ((N + 1) * (4 if E > 65535 else 2)
             + E * idx_bits // 8 + E * max(weight_bits, 8) // 8
             + book_i.nbytes + N * 1 + N * 2 + N * 2
             + (ir.n_mod_edges * (2 * idx_bits // 8 + 1) if has_mod else 0))
    ram = N * (2 + 1 + 1 + (1 if has_mod else 0)) + N * 4  # state + acc buffer
    return EmitReport(flash_B=int(flash), ram_B=int(ram), edges=E, neurons=N,
                      weight_bits=weight_bits, index_bits=idx_bits,
                      macs_per_tick_dense=E,
                      files=[str(outdir / f"{prefix}.h"), str(outdir / f"{prefix}.c"),
                             str(outdir / f"{prefix}_runtime.c")])
