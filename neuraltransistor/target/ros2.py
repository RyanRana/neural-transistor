"""Emit a ROS 2 package that runs a compiled circuit on a real robot.

Generates a complete ament_python package: node, launch file, package.xml, setup.py.
The node loads a ``.fcx`` circuit, ticks it at the morphology's control rate, and moves
data across the two boundaries the IR already defines --

    in_ports   <- sensor topics   (Image / Imu / JointState)
    out_ports  -> actuator topics (JointState / Twist)

Joint names come from the URDF-derived MorphologySpec, so the published JointState lines
up with the robot's own controllers without a translation layer.

The node runs the numpy reference by default, which is fast enough for a 200 Hz loop on
anything Linux-capable (measured: 40k tick/s for a 54k-edge circuit on a laptop). For an
MCU-class flight controller, emit C instead and use this package only for bring-up and
introspection on the companion computer.
"""

from __future__ import annotations

import textwrap
from pathlib import Path

from neuraltransistor.ir.graph import CircuitIR
from neuraltransistor.morph.spec import MorphologySpec

_NODE = '''\
"""Generated by Neural Transistor. Runs circuit "{cname}" on {mname}.

The circuit is a spiking network; a robot wants joint commands. The bridge is that fly
motor neurons are annotated by the MUSCLE they innervate, so each joint is driven by an
antagonist pair and the command is rate(agonist) - rate(antagonist). That is naturally
zero-centred, and co-contraction produces stiffness rather than motion, as in the animal.

Joint names come from the URDF this was generated against, so the published JointState
lines up with the robot's own controllers with no translation layer.
"""
import numpy as np
import rclpy
from rclpy.node import Node
from sensor_msgs.msg import JointState, Imu, Image
from geometry_msgs.msg import Twist
from std_msgs.msg import Float32MultiArray

from neuraltransistor.ir.graph import CircuitIR
from neuraltransistor.ir.runtime import Reference

CIRCUIT = "{fcx}"
JOINTS = {joints!r}
# joint name -> (agonist local indices, antagonist local indices)
JOINT_MAP = {joint_map!r}
RATE_HZ = {hz}
SENSORY_PORT_GAIN = 256.0


class Controller(Node):
    def __init__(self):
        super().__init__("neuraltransistor_{cname}")
        self.declare_parameter("circuit", CIRCUIT)
        self.declare_parameter("rate_hz", float(RATE_HZ))
        self.declare_parameter("smoothing", 0.85)
        path = self.get_parameter("circuit").value
        self.ir = CircuitIR.load(path)
        self.rt = Reference(self.ir, fast=True)
        self.smoothing = float(self.get_parameter("smoothing").value)
        self.get_logger().info(
            f"{{self.ir.n_neurons}} neurons / {{self.ir.n_edges}} edges from {{path}}; "
            f"{{len(JOINTS)}} joints, {{len(JOINT_MAP)}} driven")

        self.drive = np.zeros(self.ir.n_neurons, dtype=np.int64)
        self.rates = np.zeros(self.ir.n_neurons, dtype=np.float64)
        self.in_ports = {{p.name: p.neurons for p in self.ir.in_ports}}
        self.out_ports = {{p.name: p.neurons for p in self.ir.out_ports}}

        self.pub_joint = self.create_publisher(JointState, "joint_commands", 10)
        self.pub_twist = self.create_publisher(Twist, "cmd_vel", 10)
        self.pub_act = self.create_publisher(Float32MultiArray, "circuit_activity", 5)
        self.create_subscription(Imu, "imu", self.on_imu, 10)
        self.create_subscription(Image, "image", self.on_image, 5)
        self.create_subscription(JointState, "joint_states", self.on_joints, 10)
        self.create_timer(1.0 / float(self.get_parameter("rate_hz").value), self.step)
        self._retina = None

    # -- sensors ------------------------------------------------------------
    def on_imu(self, msg):
        """Yaw rate drives the compass. If heading drifts, check this sign first."""
        self._inject("sensory", msg.angular_velocity.z * SENSORY_PORT_GAIN)

    def on_image(self, msg):
        """Resample the frame into the ommatidial lattice and drive the visual port."""
        port = self.in_ports.get("visual_in")
        if port is None or not len(port):
            return
        try:
            img = np.frombuffer(msg.data, dtype=np.uint8).reshape(msg.height, msg.width, -1)
        except ValueError:
            return
        gray = img[..., 0].astype(np.float32) / 255.0
        if self._retina is None:
            from neuraltransistor.sensors.retina import Retina, build_resampler
            r = Retina.synthetic(n_target=len(port))
            self._retina = (r, build_resampler(r, msg.width, msg.height, hfov_deg=120.0))
        _, rs = self._retina
        vals = rs.apply(gray)
        n = min(len(port), len(vals))
        self.drive[port[:n]] = ((1.0 - vals[:n]) * 600).astype(np.int64)

    def on_joints(self, msg):
        """Proprioceptive feedback into the leg sensory port."""
        port = self.in_ports.get("sensory")
        if port is None or not len(port) or not msg.position:
            return
        pos = np.asarray(msg.position, dtype=np.float64)
        n = min(len(port), len(pos))
        self.drive[port[:n]] = (pos[:n] * 128).astype(np.int64)

    def _inject(self, port, value):
        idx = self.in_ports.get(port)
        if idx is None or not len(idx):
            return
        self.drive[idx] = int(np.clip(value, -32768, 32767))

    # -- tick ---------------------------------------------------------------
    def step(self):
        fired = self.rt.tick(self.drive)
        # low-pass the spike train into a rate; motor neurons drive muscles through a
        # calcium filter, so a raw per-tick spike is not a torque command.
        self.rates = self.smoothing * self.rates + (1.0 - self.smoothing) * fired

        js = JointState()
        js.header.stamp = self.get_clock().now().to_msg()
        js.name = list(JOINTS)
        js.velocity = [self._joint_command(j) for j in JOINTS]
        js.position = [0.0] * len(JOINTS)
        self.pub_joint.publish(js)

        act = Float32MultiArray()
        act.data = [float(self.rates.mean()), float(fired.sum())]
        self.pub_act.publish(act)

    def _joint_command(self, joint) -> float:
        """rate(agonist) - rate(antagonist) for one joint."""
        pair = JOINT_MAP.get(joint)
        if not pair:
            return 0.0
        ag, an = pair
        a = float(self.rates[ag].mean()) if ag else 0.0
        b = float(self.rates[an].mean()) if an else 0.0
        return a - b


def main():
    rclpy.init()
    n = Controller()
    try:
        rclpy.spin(n)
    finally:
        n.destroy_node()
        rclpy.shutdown()


if __name__ == "__main__":
    main()
'''


def emit_ros2(ir: CircuitIR, morph: MorphologySpec, outdir: str | Path,
              package: str = "neuraltransistor_controller",
              retarget_plan=None) -> dict:
    """Write an ament_python package under ``outdir``."""
    outdir = Path(outdir)
    pkg = outdir / package
    (pkg / package).mkdir(parents=True, exist_ok=True)
    (pkg / "launch").mkdir(exist_ok=True)
    (pkg / "resource").mkdir(exist_ok=True)

    fcx = f"{ir.name}.fcx"
    ir.save(pkg / package / fcx)
    joints = [j for l in morph.limbs for j in l.joints]

    # Resolve joint -> (agonist, antagonist) neuron indices through the retarget plan,
    # so the generated node drives each joint from its own muscle pair rather than
    # broadcasting one number to every actuator.
    joint_map: dict = {}
    if retarget_plan is not None:
        for b in retarget_plan.bindings:
            limb = next((l for l in morph.limbs if l.name == b.limb), None)
            if limb is None:
                continue
            for role, dec in b.joints.items():
                ji = limb.role_index(role)
                if ji is None:
                    continue
                joint_map[limb.joints[ji]] = (dec.agonist.tolist(),
                                              dec.antagonist.tolist())

    (pkg / package / "__init__.py").write_text("")
    (pkg / package / "node.py").write_text(_NODE.format(
        cname=ir.name.replace("-", "_"), mname=morph.name, fcx=fcx,
        joints=joints, joint_map=joint_map, hz=morph.control_hz))

    (pkg / "package.xml").write_text(textwrap.dedent(f"""\
        <?xml version="1.0"?>
        <package format="3">
          <name>{package}</name>
          <version>0.1.0</version>
          <description>Connectome-derived controller for {morph.name},
            generated by neuraltransistor from circuit "{ir.name}"
            ({ir.n_neurons} neurons, {ir.n_edges} edges).</description>
          <maintainer email="you@example.com">you</maintainer>
          <license>Apache-2.0</license>
          <depend>rclpy</depend>
          <depend>sensor_msgs</depend>
          <depend>geometry_msgs</depend>
          <export><build_type>ament_python</build_type></export>
        </package>
        """))

    (pkg / "setup.py").write_text(textwrap.dedent(f"""\
        from setuptools import setup
        package_name = "{package}"
        setup(
            name=package_name,
            version="0.1.0",
            packages=[package_name],
            data_files=[
                ("share/ament_index/resource_index/packages",
                 ["resource/" + package_name]),
                ("share/" + package_name, ["package.xml"]),
                ("share/" + package_name + "/launch", ["launch/run.launch.py"]),
            ],
            install_requires=["setuptools"],
            package_data={{package_name: ["*.fcx"]}},
            entry_points={{"console_scripts":
                ["controller = " + package_name + ".node:main"]}},
        )
        """))
    (pkg / "resource" / package).write_text("")

    (pkg / "launch" / "run.launch.py").write_text(textwrap.dedent(f"""\
        from launch import LaunchDescription
        from launch_ros.actions import Node

        def generate_launch_description():
            return LaunchDescription([
                Node(package="{package}", executable="controller",
                     name="neuraltransistor_{ir.name.replace('-', '_')}", output="screen"),
            ])
        """))

    return {"package": str(pkg), "joints": len(joints), "circuit": fcx,
            "joints_driven": len(joint_map), "control_hz": morph.control_hz,
            "files": ["package.xml", "setup.py", f"{package}/node.py",
                      f"{package}/{fcx}", "launch/run.launch.py"]}
